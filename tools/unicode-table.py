"""Writes src/text/unicode-table.ts from the C++ table (cpp/src/verbalis/text/unicode_table.h), so both
implementations classify characters identically.

    python3 tools/unicode-table.py
"""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "cpp/src/verbalis/text/unicode_table.h"
TARGET = ROOT / "ts/src/text/unicode-table.ts"

source = SOURCE.read_text(encoding="utf-8")
rows = re.findall(r"\{0x([0-9A-F]+), 0x([0-9A-F]+), (true|false)\}", source)
size = int(re.search(r"kLutSize = 0x([0-9A-F]+)", source).group(1), 16)
assert len(rows) == size, (len(rows), size)

alpha_ranges, lower, upper = [], [], []
for code, (lo, up, alpha) in enumerate(rows):
    lo, up = int(lo, 16), int(up, 16)
    if alpha == "true":
        if alpha_ranges and alpha_ranges[-1][1] == code - 1:
            alpha_ranges[-1][1] = code
        else:
            alpha_ranges.append([code, code])
    if lo != code:
        lower.append((code, lo))
    if up != code:
        upper.append((code, up))


def packed(entries):
    # Each number as one character (all are below U+D800), so the table stays one string literal in the bundle
    numbers = [n for entry in entries for n in entry]
    assert all(n < 0xD800 for n in numbers)
    return json.dumps("".join(map(chr, numbers)), ensure_ascii=False)


TARGET.write_text(
    "// Generated by tools/unicode-table.py from cpp/src/verbalis/text/unicode_table.h: do not edit.\n"
    "// Character properties of code points below TABLE_SIZE; every code point above has none. Each table is a string\n"
    "// of code points, read in pairs: a bundler prints a string literal on one line, and an array one entry a line.\n\n"
    f"export const TABLE_SIZE = 0x{size:X};\n\n"
    "function pairs(table: string): [number, number][] {\n"
    "  const codes = Array.from(table, (c) => c.codePointAt(0)!);\n"
    "  return Array.from({ length: codes.length / 2 }, (_, i) => [codes[2 * i], codes[2 * i + 1]]);\n"
    "}\n\n"
    "// Inclusive ranges of letters\n"
    f"export const ALPHA_RANGES: ReadonlyArray<readonly [number, number]> = pairs({packed(alpha_ranges)});\n\n"
    "// Code points whose lowercase or uppercase form differs from them\n"
    f"export const LOWER: ReadonlyMap<number, number> = new Map(pairs({packed(lower)}));\n"
    f"export const UPPER: ReadonlyMap<number, number> = new Map(pairs({packed(upper)}));\n",
    encoding="utf-8",
)
print(f"{TARGET}: {len(alpha_ranges)} letter ranges, {len(lower)} lowercase and {len(upper)} uppercase mappings")
